fn step_verify(ctx: &Ctx) {
    ctx.head("14/14 自检");

    fn version_arg(name: &str) -> &'static str {
        match name {
            "go" | "gopls" | "dlv" => "version",
            "codelldb" => "--help",
            _ => "--version",
        }
    }

    // 顺序 mason -> ~/.local/bin -> PATH -> ~/.cargo/bin；
    // 不能先查 PATH，否则会命中 rust-analyzer 的 rustup shim。
    fn resolve(ctx: &Ctx, name: &str) -> Option<PathBuf> {
        for p in [ctx.mason_bin.join(name), ctx.local_bin.join(name)] {
            if p.is_file() {
                return Some(p);
            }
        }
        if have(name) {
            let which = first_line("sh", &["-c", &format!("command -v {}", name)]);
            if !which.is_empty() && which != format!("{}/.cargo/bin/rust-analyzer", ctx.home.display()) {
                return Some(PathBuf::from(which));
            }
        }
        if name != "rust-analyzer" {
            let p = ctx.home.join(".cargo").join("bin").join(name);
            if p.is_file() {
                return Some(p);
            }
        }
        None
    }

    for name in ["go", "rustc", "cargo", "rust-analyzer", "codelldb",
                 "clangd", "gopls", "pyright", "ruff", "dlv"] {
        match resolve(ctx, name) {
            Some(p) => {
                if name == "codelldb" {
                    ctx.ok(&format!("{:<14} 可用 -> {}", name, p.display()));
                } else {
                    let ver = first_line(&p.to_string_lossy(), &[version_arg(name)]);
                    ctx.ok(&format!("{:<14} {}", name, if ver.is_empty() { "?" } else { &ver }));
                }
            }
            None => ctx.warn(&format!("{:<14} 缺失", name)),
        }
    }

    if !have("nvim") {
        ctx.warn("    未安装 nvim，跳过配置自检");
        return;
    }

    let out_file = env::temp_dir().join(format!("nvimcheck-{}.txt", pid()));
    let lua_file = env::temp_dir().join(format!("nvimcheck-{}.lua", pid()));
    let lua = format!(r#"
OUT_FILE = "{}"
local out = {{}}
local function p(s) table.insert(out, s) end
p('lazy.nvim: ' .. tostring(pcall(require, 'lazy')))
local events, has_i, has_swap = {{}}, false, false
for _, a in ipairs(vim.api.nvim_get_autocmds({{ group = 'UserAutoSave' }})) do
  table.insert(events, a.event)
  if a.event == 'CursorHoldI' then has_i = true end
  if a.event == 'SwapExists' then has_swap = true end
end
table.sort(events)
p('自动保存组: ' .. #events .. ' 条 [' .. table.concat(events, ',') .. ']')
p('插入模式兜底(CursorHoldI): ' .. tostring(has_i))
p('崩溃恢复(SwapExists): ' .. tostring(has_swap))
p('定时保存间隔: ' .. tostring(vim.g.autosave_interval or 5000) .. 'ms')
p('交换文件目录: ' .. vim.o.directory .. (vim.o.directory:sub(-2) == '//' and ' (含 //，正确)' or ' (缺 //，需修正)'))
-- 等 VeryLazy 阶段的插件（dap-go 等）把调试配置注册完，
-- 否则同一份配置每次统计出来数目都不一样
vim.wait(800, function() return false end, 100)
local okd, dap = pcall(require, 'dap')
if okd then
  local fts = {{}}
  for k, v in pairs(dap.configurations) do
    -- 只报语言名，不报条数：条数会随插件注册时机浮动
    if type(v) == 'table' and #v > 0 then table.insert(fts, k) end
  end
  table.sort(fts)
  p('调试配置: ' .. (#fts > 0 and table.concat(fts, ', ') or '无'))
end
local okp, paths = pcall(require, 'core.paths')
if okp then
  for _, n in ipairs({{ 'rust-analyzer', 'codelldb', 'gopls', 'clangd', 'pyright', 'ruff' }}) do
    p(string.format('%-16s %s', n, paths.resolve(n)))
  end
end
local f = io.open(OUT_FILE, 'w')
if f then f:write(table.concat(out, '\n') .. '\n'); f:close() end
"#, out_file.display());

    let _ = fs::write(&lua_file, lua);
    ctx.log("    配置内自检：");
    let _ = Command::new("nvim")
        .args(["--headless", "-u"])
        .arg(ctx.nvim_config.join("init.lua"))
        .args(["-c"])
        .arg(format!("luafile {}", lua_file.display()))
        .args(["-c", "qa!"])
        .stdout(Stdio::null())
        .stderr(Stdio::null())
        .status();

    match fs::read_to_string(&out_file) {
        Ok(text) if !text.trim().is_empty() => {
            for line in text.trim().lines() {
                ctx.log(&format!("      {}", line));
            }
        }
        _ => ctx.warn("    自检无输出（配置可能加载失败，手动运行 nvim 看报错）"),
    }
    let _ = fs::remove_file(&lua_file);
    let _ = fs::remove_file(&out_file);
}

