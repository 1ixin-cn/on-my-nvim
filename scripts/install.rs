fn step_deploy_config(ctx: &Ctx) {
    ctx.head("3/14 部署配置（内嵌归档）");
    if ctx.check {
        ctx.log("    体检模式：跳过部署");
        return;
    }

    match &ctx.from_dir {
        Some(src) => {
            if !src.join("init.lua").is_file() || !src.join("lua").is_dir() {
                ctx.err(&format!("--from-dir {} 下没有 init.lua / lua", src.display()));
                std::process::exit(1);
            }
            for item in ["init.lua", "lua", "lazy-lock.json", "README.md", "快捷键手册.md"] {
                let s = src.join(item);
                if !s.exists() {
                    continue;
                }
                let d = ctx.nvim_config.join(item);
                if d.is_dir() {
                    let _ = fs::remove_dir_all(&d);
                } else {
                    let _ = fs::remove_file(&d);
                }
                if s.is_dir() {
                    let _ = run_sh(&format!("cp -R {} {}", shell_quote(&s.to_string_lossy()), shell_quote(&d.to_string_lossy())));
                } else {
                    let _ = fs::copy(&s, &d);
                }
            }
            ctx.ok(&format!("    已从 {} 部署", src.display()));
        }
        None => match extract_payload(ctx, &ctx.nvim_config) {
            Ok(()) => ctx.ok("    已解出内嵌配置"),
            Err(e) => {
                ctx.err(&e);
                std::process::exit(1);
            }
        },
    }

    if !ctx.nvim_config.join("init.lua").is_file() {
        ctx.err("部署后缺少 init.lua");
        std::process::exit(1);
    }
    let autosave = ctx.nvim_config.join("lua").join("core").join("autosave.lua");
    if !autosave.is_file() {
        ctx.err("部署后缺少 core/autosave.lua");
        std::process::exit(1);
    }
    if let Ok(text) = fs::read_to_string(&autosave) {
        if !text.contains("UserAutoSave") {
            ctx.warn("    配置里没找到 UserAutoSave，可能版本不对");
        }
    }

    // 把自己也放进配置目录，方便以后重跑
    let scripts = ctx.nvim_config.join("scripts");
    let _ = fs::create_dir_all(&scripts);
    if let Ok(exe) = env::current_exe() {
        let target = scripts.join("install");
        if exe != target {
            let _ = fs::copy(&exe, &target);
        }
    }

    let count = walk_count(&ctx.nvim_config);
    ctx.ok(&format!("    配置文件数: {}", count));
}

fn walk_count(dir: &Path) -> usize {
    let mut n = 0;
    if let Ok(rd) = fs::read_dir(dir) {
        for e in rd.flatten() {
            let p = e.path();
            if p.is_dir() {
                n += walk_count(&p);
            } else {
                n += 1;
            }
        }
    }
    n
}

