struct Ctx {
    home: PathBuf,
    nvim_config: PathBuf,
    nvim_data: PathBuf,
    local_bin: PathBuf,
    mason_bin: PathBuf,
    codelldb_root: PathBuf,
    lazy_dir: PathBuf,
    vimcdoc_dir: PathBuf,
    log_dir: PathBuf,
    check: bool,
    force: bool,
    skip_plugins: bool,
    skip_mason: bool,
    from_dir: Option<PathBuf>,
    no_color: bool,
}

impl Ctx {
    fn new() -> Ctx {
        let home = PathBuf::from(env::var("HOME").unwrap_or_else(|_| "/tmp".into()));
        let data = env::var("XDG_DATA_HOME")
            .map(PathBuf::from)
            .unwrap_or_else(|_| home.join(".local").join("share"));
        let nvim_data = data.join("nvim");
        let nvim_config = env::var("NVIM_CONFIG")
            .map(PathBuf::from)
            .unwrap_or_else(|_| home.join(".config").join("nvim"));
        Ctx {
            log_dir: home.join(".cache").join("nvim-install"),
            local_bin: home.join(".local").join("bin"),
            mason_bin: nvim_data.join("mason").join("bin"),
            codelldb_root: env::var("CODELLDB_ROOT")
                .map(PathBuf::from)
                .unwrap_or_else(|_| home.join(".local").join("share").join("codelldb")),
            lazy_dir: nvim_data.join("lazy").join("lazy.nvim"),
            vimcdoc_dir: nvim_data.join("plugins-local").join("vimcdoc"),
            nvim_data,
            nvim_config,
            home,
            check: false,
            force: false,
            skip_plugins: false,
            skip_mason: false,
            from_dir: None,
            no_color: env::var("NO_COLOR").is_ok(),
        }
    }

    fn c<'a>(&self, code: &'a str) -> &'a str {
        if self.no_color { "" } else { code }
    }

    fn log_file(&self) -> PathBuf {
        self.log_dir.join("install.rs.log")
    }

    fn write_log(&self, plain: &str) {
        let _ = fs::create_dir_all(&self.log_dir);
        if let Ok(mut f) = fs::OpenOptions::new()
            .create(true)
            .append(true)
            .open(self.log_file())
        {
            let _ = writeln!(f, "{}", plain);
        }
    }

    fn log(&self, msg: &str) {
        println!("{}", msg);
        self.write_log(msg);
    }
    fn ok(&self, msg: &str) {
        let line = format!("{}✓{} {}", self.c(GREEN), self.c(RESET), msg);
        println!("{}", line);
        self.write_log(&format!("✓ {}", msg));
    }
    fn warn(&self, msg: &str) {
        let line = format!("{}!{} {}", self.c(YELLOW), self.c(RESET), msg);
        println!("{}", line);
        self.write_log(&format!("! {}", msg));
    }
    fn err(&self, msg: &str) {
        let line = format!("{}✗{} {}", self.c(RED), self.c(RESET), msg);
        println!("{}", line);
        self.write_log(&format!("✗ {}", msg));
    }
    fn head(&self, msg: &str) {
        let line = format!("\n{}{}==> {}{}", self.c(BOLD), self.c(BLUE), msg, self.c(RESET));
        println!("{}", line);
        self.write_log(&format!("==> {}", msg));
    }
    fn step_done(&self, msg: &str) {
        self.ok(&format!("{}（已存在，跳过）", msg));
    }
}

// ---------------------------------------------------------------- 进程工具
fn have(cmd: &str) -> bool {
    Command::new("sh")
        .arg("-c")
        .arg(format!("command -v {} >/dev/null 2>&1", shell_quote(cmd)))
        .status()
        .map(|s| s.success())
        .unwrap_or(false)
}

fn shell_quote(s: &str) -> String {
    format!("'{}'", s.replace('\'', "'\\''"))
}

/// 静默执行，返回 (成功, 输出)
fn run_capture(program: &str, args: &[&str]) -> (bool, String) {
    match Command::new(program)
        .args(args)
        .stdout(Stdio::piped())
        .stderr(Stdio::piped())
        .output()
    {
        Ok(o) => {
            let mut s = String::from_utf8_lossy(&o.stdout).to_string();
            s.push_str(&String::from_utf8_lossy(&o.stderr));
            (o.status.success(), s)
        }
        Err(e) => (false, e.to_string()),
    }
}

fn run_sh(script: &str) -> bool {
    Command::new("sh")
        .arg("-c")
        .arg(script)
        .status()
        .map(|s| s.success())
        .unwrap_or(false)
}

fn first_line(program: &str, args: &[&str]) -> String {
    let (_, out) = run_capture(program, args);
    out.lines()
        .find(|l| !l.trim().is_empty())
        .unwrap_or("")
        .trim()
        .to_string()
}

fn arch_assets() -> (&'static str, &'static str) {
    let arch = String::from_utf8_lossy(
        &Command::new("uname").arg("-m").output().map(|o| o.stdout).unwrap_or_default(),
    )
    .trim()
    .to_string();
    if arch == "x86_64" {
        ("codelldb-darwin-x64.vsix", "rust-analyzer-x86_64-apple-darwin.gz")
    } else {
        ("codelldb-darwin-arm64.vsix", "rust-analyzer-aarch64-apple-darwin.gz")
    }
}

fn download(ctx: &Ctx, url: &str, dest: &Path) -> bool {
    ctx.log(&format!("    下载 {}", url));
    Command::new("curl")
        .args(["-fL", "--retry", "3", "--retry-delay", "2", "--connect-timeout", "15",
               "--progress-bar", "-o"])
        .arg(dest)
        .arg(url)
        .status()
        .map(|s| s.success())
        .unwrap_or(false)
}

fn clone_or_tarball(ctx: &Ctx, repo: &str, branch: &str, dest: &Path, name: &str) -> bool {
    if let Some(parent) = dest.parent() {
        let _ = fs::create_dir_all(parent);
    }
    if dest.join(".git").is_dir() {
        return true;
    }

    let url = format!("https://github.com/{}.git", repo);
    let cloned = Command::new("git")
        .args(["clone", "--depth", "1", "--branch", branch, &url])
        .arg(dest)
        .stdout(Stdio::null())
        .stderr(Stdio::null())
        .status()
        .map(|s| s.success())
        .unwrap_or(false);
    if cloned {
        ctx.ok(&format!("    {}: git clone 成功", name));
        return true;
    }

    ctx.warn(&format!("    {}: git clone 失败（多为代理拦 git 协议），改用 codeload 压缩包", name));
    let tar_url = format!("https://codeload.github.com/{}/tar.gz/refs/heads/{}", repo, branch);
    let tmp = env::temp_dir().join(format!("nvimtar-{}.tar.gz", pid()));
    if !download(ctx, &tar_url, &tmp) {
        let _ = fs::remove_file(&tmp);
        return false;
    }
    let _ = fs::remove_dir_all(dest);
    let _ = fs::create_dir_all(dest);

    let ok = Command::new("tar")
        .args(["-xzf"])
        .arg(&tmp)
        .arg("-C")
        .arg(dest)
        .arg("--strip-components")
        .arg("1")
        .status()
        .map(|s| s.success())
        .unwrap_or(false);
    let _ = fs::remove_file(&tmp);
    if !ok {
        return false;
    }
    // 登记成 git 仓库，免得 lazy 反复尝试联网
    let _ = Command::new("git").args(["init", "-q"]).current_dir(dest).status();
    let _ = Command::new("git").args(["add", "-A"]).current_dir(dest).status();
    let _ = Command::new("git")
        .args(["-c", "user.email=install@local", "-c", "user.name=install",
               "commit", "-qm", "install"])
        .current_dir(dest)
        .status();
    ctx.ok(&format!("    {}: 已用压缩包安装", name));
    true
}

