fn usage() {
    println!("Neovim 类 IDE 一键部署（Rust 版）\n\n\
用法：\n  \
./install                  完整部署（幂等，已装的跳过）\n  \
./install --check          只体检，不改任何东西\n  \
./install --force          已存在也强制重装\n  \
./install --from-dir DIR   从本地目录部署配置\n  \
./install --skip-plugins   跳过插件同步\n  \
./install --skip-mason     跳过 Mason 工具安装\n  \
./install --dump-config D  只把内嵌配置解到目录 D\n  \
./install --help           显示本帮助\n\n\
日志：~/.cache/nvim-install/install.rs.log");
}

fn main() {
    let mut ctx = Ctx::new();
    let args: Vec<String> = env::args().skip(1).collect();
    let mut dump_config: Option<String> = None;
    let mut i = 0;
    while i < args.len() {
        match args[i].as_str() {
            "--check" => ctx.check = true,
            "--force" => ctx.force = true,
            "--skip-plugins" => ctx.skip_plugins = true,
            "--skip-mason" => ctx.skip_mason = true,
            "--from-dir" => {
                i += 1;
                if i < args.len() {
                    ctx.from_dir = Some(PathBuf::from(&args[i]));
                }
            }
            "--dump-config" => {
                i += 1;
                if i < args.len() {
                    dump_config = Some(args[i].clone());
                }
            }
            "-h" | "--help" => {
                usage();
                return;
            }
            other => {
                eprintln!("未知参数: {}（用 --help 查看用法）", other);
                std::process::exit(2);
            }
        }
        i += 1;
    }

    if let Some(dir) = dump_config {
        match extract_payload(&ctx, &PathBuf::from(&dir)) {
            Ok(()) => ctx.ok(&format!("配置已解到 {}", dir)),
            Err(e) => {
                ctx.err(&e);
                std::process::exit(1);
            }
        }
        return;
    }

    let _ = fs::create_dir_all(&ctx.log_dir);
    println!("{}{}Neovim 类 IDE 一键部署（Rust）{}", ctx.c(BOLD), ctx.c(BLUE), ctx.c(RESET));
    ctx.log(&format!("日志:     {}", ctx.log_file().display()));
    ctx.log(&format!("目标:     {}", ctx.nvim_config.display()));
    ctx.log(&format!("配置来源: {}",
        ctx.from_dir.as_ref().map(|p| p.display().to_string()).unwrap_or_else(|| "脚本内嵌归档".into())));

    step_preflight(&ctx);
    step_backup(&ctx);
    step_deploy_config(&ctx);
    step_homebrew(&ctx);
    step_rust(&ctx);
    step_rust_analyzer(&ctx);
    step_codelldb(&ctx);
    step_python(&ctx);
    step_lazy(&ctx);
    step_plugins(&ctx);
    step_mason(&ctx);
    step_vimcdoc(&ctx);
    step_path(&ctx);
    step_verify(&ctx);

    println!();
    ctx.ok("部署流程结束");
    println!("\n{}下一步{}", ctx.c(BOLD), ctx.c(RESET));
    println!("  1. 重新打开终端（或 source ~/.zshrc）让 PATH 生效");
    println!("  2. 运行 nvim，首次会自动补装剩余插件/工具");
    println!("  3. 随便改个文件停手 1 秒，确认已自动写盘");
    println!("  4. 快捷键手册: {}/快捷键手册.md", ctx.nvim_config.display());
}
